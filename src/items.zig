/// Deterministic fortress junction loot roll for world (wx, wz).
pub fn fortressLoot(wx: i32, wz: i32, out: *[4]ItemStack) void {
    const h1: u32 = @as(u32, @bitCast(wx *% 17 +% wz *% 41)) % 3;
    const h2: u32 = @as(u32, @bitCast(wx *% 29 +% wz *% 53)) % 2;
    out[0] = .{ .item = .nether_wart, .count = @as(u8, @intCast(h1 + 2)) };
    out[1] = .{ .item = .nether_quartz, .count = @as(u8, @intCast(h2 + 1)) };
    const h3: u32 = @as(u32, @bitCast(wx *% 11 +% wz *% 67)) % 4;
    if (h3 == 0) {
        out[2] = .{ .item = .iron_ingot, .count = 2 };
    } else {
        out[2] = .{};
    }
    const h4: u32 = @as(u32, @bitCast(wx *% 19 +% wz *% 73)) % 4;
    if (h4 == 0) {
        out[3] = .{ .item = .music_disc_13, .count = 1 };
    } else if (h4 == 1) {
        out[3] = .{ .item = .music_disc_cat, .count = 1 };
    } else {
        out[3] = .{};
    }
}

test "ItemType block roundtrips, ItemStack operations, and getBlockDrops" {
    const item = ItemType.fromBlockId(.stone);
    try std.testing.expectEqual(item, ItemType.stone);
    try std.testing.expectEqual(item.toBlockId(), .stone);

    var stack = ItemStack{ .item = .dirt, .count = 10 };
    try std.testing.expect(!stack.isEmpty());
    const rem = stack.add(5);
    try std.testing.expectEqual(@as(u8, 0), rem);
    try std.testing.expectEqual(@as(u8, 15), stack.count);
    stack.decrement(5);
    try std.testing.expectEqual(@as(u8, 10), stack.count);
    stack.clear();
    try std.testing.expect(stack.isEmpty());

    var drops: [4]BlockDrop = undefined;
    const n = getBlockDrops(.gilded_blackstone, &drops);
    try std.testing.expectEqual(@as(usize, 2), n);
    try std.testing.expectEqual(drops[0].item, ItemType.blackstone);
    try std.testing.expectEqual(drops[1].item, ItemType.gold_nugget);
}

